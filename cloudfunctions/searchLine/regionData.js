// 名字统一存自然写法，查询时经 norm() 去掉 市/区/县/省 等后缀后比对。

function norm(s) {
  if (!s) return '';
  return String(s).trim().replace(/(市|区|县|省|自治州|盟|地区)$/, '');
}

