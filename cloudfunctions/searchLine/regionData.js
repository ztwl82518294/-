// 构建 子地区规范名 → [父地区] 映射（同名多地归属，如 朝阳→北京/辽宁，均保留）
const CHILD_PARENTS = {};
function addChildren(parent, children) {
  (children || []).forEach(c => {
    const key = norm(c);
    if (!key) return;
    (CHILD_PARENTS[key] = CHILD_PARENTS[key] || []).push(parent);
  });
}
Object.keys(MUNICIPALITIES).forEach(p => addChildren(p, MUNICIPALITIES[p]));
Object.keys(PROVINCE_CITIES).forEach(p => addChildren(p, PROVINCE_CITIES[p]));
Object.keys(CITY_COUNTIES).forEach(c => addChildren(c, CITY_COUNTIES[c]));

// 查询某地名的直接上级地区列表；未知地名返回 []
function parentsOf(name) {
  return CHILD_PARENTS[norm(name)] || [];
}

// 递归查询某地名的所有上级地区（含省/市/区县多级），用于省份级全境匹配
function allParentsOf(name, visited) {
  visited = visited || new Set();
  const key = norm(name);
  if (!key || visited.has(key)) return [];
  visited.add(key);
  const direct = parentsOf(key);
  const result = direct.slice();
  direct.forEach(p => {
    allParentsOf(p, visited).forEach(pp => {
      if (result.indexOf(pp) === -1) result.push(pp);
    });
  });
  return result;
}

// 判断是否为地级市（含直辖市、自治州、地区、盟）
const PREFECTURE_KEYS = new Set([
  ...Object.keys(MUNICIPALITIES),
  ...Object.keys(PROVINCE_CITIES),
  ...Object.keys(CITY_COUNTIES)
]);
function isPrefecture(name) {
  return PREFECTURE_KEYS.has(norm(name));
}

// 获取城市级名称：
//   区县 → 返回其上级地级市；
//   地级市/直辖市/省份 → 返回自身归一化名
function getCityLevel(name) {
  if (!name) return '';
  const n = norm(name);
  if (isPrefecture(n)) return n;
  const parents = parentsOf(name);
  return parents.length > 0 ? parents[0] : n;
}

module.exports = { parentsOf, allParentsOf, norm, isPrefecture, getCityLevel };
