// .workbuddy/scripts/sync-region-data.js
// 从 cloudfunctions/searchLine/regionData.js 生成小程序端 utils/region-data.js。
//
// 背景：地区选择弹层（components/region-picker）需要省市县三级数据，
//       而小程序端不能 require 云函数目录。为守住"搜索匹配与展示同一套数据"这条护栏，
//       采用"云函数文件为唯一源 → 脚本生成前端副本"的方式，而不是让前端手抄一份。
//
// 用法：node .workbuddy/scripts/sync-region-data.js
// 改完 regionData.js 必须重跑本脚本，否则前后端数据会漂移。
//
// 注意：输出文件严禁带 BOM（微信编译器会在第 1 行报 unexpected '\uFEFF'）。

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const SRC = path.join(ROOT, 'cloudfunctions', 'searchLine', 'regionData.js');
const DEST = path.join(ROOT, 'utils', 'region-data.js');

function main() {
  if (!fs.existsSync(SRC)) {
    console.error('[sync-region-data] 源文件不存在：' + SRC);
    process.exit(1);
  }
  const src = fs.readFileSync(SRC, 'utf8');

  // 用正则切出三张原始表（保持字面量原样，不做解析再序列化，避免格式漂移）
  function slice(name) {
    const re = new RegExp('const ' + name + ' = (\\{[\\s\\S]*?\\n\\});');
    const m = src.match(re);
    if (!m) throw new Error('未能从源文件切出 ' + name);
    return m[1];
  }

  let MUNICIPALITIES, PROVINCE_CITIES, CITY_COUNTIES;
  try {
    MUNICIPALITIES = slice('MUNICIPALITIES');
    PROVINCE_CITIES = slice('PROVINCE_CITIES');
    CITY_COUNTIES = slice('CITY_COUNTIES');
  } catch (e) {
    console.error('[sync-region-data] ' + e.message);
    process.exit(1);
  }

  const out = buildOutput(MUNICIPALITIES, PROVINCE_CITIES, CITY_COUNTIES);

  fs.writeFileSync(DEST, out, { encoding: 'utf8' }); // 默认不带 BOM

  // 自检：确认没有 BOM
  const head = fs.readFileSync(DEST).slice(0, 3);
  if (head[0] === 0xEF && head[1] === 0xBB && head[2] === 0xBF) {
    console.error('[sync-region-data] 输出被写入了 BOM，请检查写入方式');
    process.exit(1);
  }

  // 自检：生成的模块能被正常 require，且展示名有映射
  let mod;
  try {
    delete require.cache[require.resolve(DEST)];
    mod = require(DEST);
  } catch (e) {
    console.error('[sync-region-data] 生成的模块无法加载：' + e.message);
    process.exit(1);
  }
  const nanchong = (mod.CITY_COUNTIES['南充'] || []).map(mod.displayName);
  if (nanchong.indexOf('高坪区') === -1) {
    console.error('[sync-region-data] 展示名映射异常，南充样本解析为：' + nanchong.join('/'));
    process.exit(1);
  }

  const counts = [
    countKeys(MUNICIPALITIES), countKeys(PROVINCE_CITIES), countKeys(CITY_COUNTIES)
  ];
  console.log('[sync-region-data] 已生成 ' + path.relative(ROOT, DEST));
  console.log('  直辖市 ' + counts[0] + ' 个 / 省级 ' + counts[1] + ' 个 / 地级市 ' + counts[2] + ' 个');
  console.log('  样本校验：南充 → ' + nanchong.join(' / '));
}

function countKeys(literal) {
  return (literal.match(/^\s*'/gm) || []).length;
}

