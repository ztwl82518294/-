/** 是否已同意过隐私规则 */
function hasAgreed() {
  try {
    return wx.getStorageSync(STORAGE_KEY) === true;
  } catch (e) {
    // 存储不可用时按「未同意」处理，宁可多弹一次也不漏合规
    return false;
  }
}

/** 标记为已同意 */
function markAgreed() {
  try {
    wx.setStorageSync(STORAGE_KEY, true);
    return true;
  } catch (e) {
    return false;
  }
}

/** 清除同意标记（调试用，需传 force 参数） */
function resetAgreed() {
  try {
    wx.removeStorageSync(STORAGE_KEY);
    return true;
  } catch (e) {
    return false;
  }
}

